import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# ==========================================================
# 1. LOAD DATASET (Kondisi Asli / Orisinil)
# ==========================================================
file_path = "dataKasus-1.xlsx"
df = pd.read_excel(file_path)

print("=" * 60)
print("  PERTEMUAN 2: ANALISIS ATRIBUT & DATA UNDERSTANDING (CRISP-DM)")
print("=" * 60)

# ==========================================================
# 2. METADATA & PEMETAAN TIPE ATRIBUT (Slide 3 & 4)
# ==========================================================
print(f"\n[1] METADATA DATASET")
print(f"- Jumlah Baris (Record) : {df.shape[0]}")
print(f"- Jumlah Kolom (Atribut): {df.shape[1]}")

# Pemetaan Tipe Atribut berdasarkan Teori Data Mining:
# Nominal  : Kategorikal tanpa urutan
# Ordinal  : Kategorikal memiliki tingkatan/urutan
# Ratio    : Numerik kontinu/diskrit dengan titik nol mutlak
tipe_atribut = {
    'NO': 'Nominal (Identifier Key)',
    'NAMA': 'Nominal (Label/Text)',
    'USIA': 'Ratio / Numerik (Format awal string "TH")',
    'PARITAS': 'Ratio / Numerik (Jumlah persalinan)',
    'JARAK KELAHIRAN': 'Ordinal (Kategori berurutan: anak pertama < <2 thn < >2 thn)',
    'RIW HIPERTENSI': 'Nominal (Binary: Tidak/Ya)',
    'RIW PE': 'Nominal (Kategori Diagnosis Preeklampsia)',
    'OBESITAS': 'Nominal (Binary: Tidak/Ya)',
    'RIW DM': 'Nominal (Binary: Tidak/Ya)',
    'RIW HIPERTENSI/PE DALAM KELUARGA': 'Nominal (Binary: Tidak/Ada)',
    'SOSEK RENDAH': 'Ordinal (Kategori Ekonomi: <UMR / >UMR)',
    'PE/Non PE': 'Nominal (Target / Class Label)',
    'Unnamed: 12': 'Nominal (Catatan Khusus / Unstructured)'
}

print("\n[2] PEMETAAN TIPE ATRIBUT DATA:")
for col, ttype in tipe_atribut.items():
    print(f"  • {col:<35}: {ttype}")

# ==========================================================
# 3. ANALISIS KUALITAS DATA (Slide 32-34)
# ==========================================================
print("\n" + "=" * 60)
print("  ANALISIS KUALITAS DATA")
print("=" * 60)

# a. Missing Values Check (Slide 32)
print("\na. Missing Values (Nilai Hilang):")
missing = df.isnull().sum()
missing_filtered = missing[missing > 0]
if not missing_filtered.empty:
    for col, count in missing_filtered.items():
        persen = (count / len(df)) * 100
        print(f"  • Kolom '{col}': {count} record kosong ({persen:.2f}%)")
else:
    print("  • Tidak ditemukan missing values.")

# b. Class Distribution & Imbalance Check (Slide 34)
print("\nb. Analisis Unbalanced Data (Class Imbalance pada Target 'PE/Non PE'):")
class_dist = df['PE/Non PE'].value_counts()
print(class_dist)

# Pengelompokan Biner (Non PE vs Kasus Preeklampsia/PE)
pe_group = df['PE/Non PE'].apply(lambda x: 'Non PE' if x == 'Non PE' else 'Kasus PE / Risiko High')
pe_summary = pe_group.value_counts()
print("\nRingkasan Proporsi Target:")
for k, v in pe_summary.items():
    print(f"  • {k}: {v} sampel ({v/len(df)*100:.2f}%)")

# ==========================================================
# 4. VISUALISASI EKSPLORASI DATA (Slide 35)
# ==========================================================
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Plot 1: Distribusi Target Class Imbalance
sns.countplot(x=pe_group, ax=axes[0], palette="Set2")
axes[0].set_title("Distribusi Class Target (PE vs Non PE)")
axes[0].set_xlabel("Kategori Diagnosa")
axes[0].set_ylabel("Jumlah Pasien")

# Plot 2: Paritas berdasarkan Risiko PE
sns.countplot(data=df, x='PARITAS', hue=pe_group, ax=axes[1], palette="Set1")
axes[1].set_title("Distribusi Paritas berdasarkan Status PE")
axes[1].set_xlabel("Paritas (Jumlah Anak)")
axes[1].set_ylabel("Jumlah Pasien")

plt.tight_layout()
plt.savefig("distribusi_atribut_pertemuan2.png")
plt.show()

print("\n Visualisasi berhasil disimpan sebagai 'distribusi_atribut_pertemuan2.png'.")