import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# ==========================================
# 1. TINGKAT DATA (Data Mentah / Transaksional)
# Fakta terekam tanpa arti spesifik
# ==========================================
data_absensi = {
    'ID_Karyawan': ['ID001', 'ID002', 'ID003', 'ID004', 'ID005'] * 4,
    'Hari': ['Senin', 'Senin', 'Senin', 'Senin', 'Senin',
             'Rabu', 'Rabu', 'Rabu', 'Rabu', 'Rabu',
             'Jumat', 'Jumat', 'Jumat', 'Jumat', 'Jumat',
             'Senin', 'Senin', 'Senin', 'Senin', 'Senin'],
    'Status': ['Terlambat', 'Hadir', 'Terlambat', 'Terlambat', 'Terlambat',
               'Hadir', 'Hadir', 'Hadir', 'Hadir', 'Hadir',
               'Pulang Awal', 'Pulang Awal', 'Hadir', 'Pulang Awal', 'Pulang Awal',
               'Terlambat', 'Hadir', 'Terlambat', 'Terlambat', 'Hadir']
}

df_data = pd.DataFrame(data_absensi)
print("=== 1. LEVEL DATA (Raw Data) ===")
print(df_data.head(10))
print("\n")

# ==========================================
# 2. TINGKAT INFORMASI (Rekap & Statistik)
# Data yang sudah diolah dan dirangkum
# ==========================================
rekap_status = df_data.groupby(['Hari', 'Status']).size().unstack(fill_value=0)

print("=== 2. LEVEL INFORMASI (Rekap Kehadiran) ===")
print(rekap_status)
print("\n")

# ==========================================
# 3. TINGKAT PENGETAHUAN (Ekstraksi Pola / Pattern)
# Menemukan kebiasaan atau tren tersembunyi
# ==========================================
plt.figure(figsize=(8, 5))
sns.heatmap(rekap_status, annot=True, cmap="YlGnBu", fmt="d", cbar=False)
plt.title("Pola Kebiasaan Kehadiran Karyawan berdasarkan Hari")
plt.xlabel("Status Kehadiran")
plt.ylabel("Hari Kerja")
plt.tight_layout()
plt.savefig("pola_kehadiran.png")
plt.show()

print("=== 3. LEVEL PENGETAHUAN (Pola yang Ditemukan) ===")
print("- Karyawan cenderung sering TERLAMBAT pada hari SENIN.")
print("- Karyawan cenderung sering PULANG AWAL pada hari JUMAT.")
print("- Kehadiran relatif stabil dan normal pada hari RABU.")
print("\n")

# ==========================================
# 4. TINGKAT KEBIJAKAN (Actionable Decisions)
# Keputusan strategis berbasis pengetahuan
# ==========================================
def rekomendasi_kebijakan(hari):
    if hari == 'Senin':
        return "Kebijakan: Jam masuk hari Senin dimundurkan jadi jam 10:00 WIB."
    elif hari == 'Jumat':
        return "Kebijakan: Jam kerja hari Jumat diakhiri jam 14:00 WIB."
    else:
        return "Kebijakan: Jam kerja normal."

print("=== 4. LEVEL KEBIJAKAN (Rekomendasi Manajerial) ===")
for h in ['Senin', 'Rabu', 'Jumat']:
    print(rekomendasi_kebijakan(h))